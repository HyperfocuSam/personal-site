const fs = require('fs');

const postsDirectory = 'src/data/posts';
const outputFile = `${postsDirectory}/content.generated.js`;

const postContent = Object.fromEntries(
  fs.readdirSync(postsDirectory)
    .filter((filename) => filename.endsWith('.md'))
    .sort()
    .map((filename) => [
      filename.slice(0, -3),
      fs.readFileSync(`${postsDirectory}/${filename}`, 'utf8'),
    ]),
);

const generatedModule = `// GENERATED by scripts/generate-post-content.js — do not edit
/* eslint-disable quotes, comma-dangle */

const postContent = ${JSON.stringify(postContent, null, 2)};

export default postContent;
`;

fs.writeFileSync(outputFile, generatedModule, 'utf8');
console.log(`Post content generated: ${Object.keys(postContent).length} posts`);

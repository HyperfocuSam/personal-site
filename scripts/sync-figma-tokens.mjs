// Figma -> SCSS token sync  (Stage 2 of the design-to-code bridge)
// ---------------------------------------------------------------------------
// WHAT THIS DOES
//   Reads a snapshot of the Figma brand variables (../figma-tokens.json) and
//   writes the CORE brand colours into a generated SCSS partial:
//       src/static/css/libs/_tokens.figma.generated.scss
//   That partial defines a $figma-tokens map. _vars.scss merges it over its
//   own $palette so the Figma values win for the core brand colours, while
//   the codebase keeps its extended/derived tokens (Stage 3 wires that up).
//
// RUN
//   node scripts/sync-figma-tokens.mjs
//
// THE CONTRACT (the only part a human owns)
//   Figma names the brand colours one way ("color/bg"); this codebase's
//   $palette names them another ("surface-base"). COLOR_MAP below IS that
//   contract: the single place you decide which Figma token maps to which
//   $palette key(s). Edit the map when you add or rename a token. Never edit
//   the generated .scss by hand -- it is overwritten every run.
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const IN = join(ROOT, 'figma-tokens.json');
const OUT = join(ROOT, 'src/static/css/libs/_tokens.figma.generated.scss');

// One Figma variable can feed more than one $palette key (e.g. ink is both
// `ink` and `text-primary`). The array on the right makes that explicit.
const COLOR_MAP = {
  // Brand v1.0 (2026-08-02): the legacy amber keys carry heritage gold, the
  // legacy amber-text carries signal-deep, and verified/trust marks carry
  // heritage — same contract as the (now retired) $samwong-arsenal-v1 core.
  'color/ink':           ['ink', 'text-primary'],
  'color/inkMid':        ['ink-mid'],
  'color/inkSoft':       ['ink-light'],
  'color/signal':        ['signal'],
  'color/signalDeep':    ['signal-deep', 'amber-text'],
  'color/heritage':      ['heritage', 'amber', 'verification', 'tag-green'],
  'color/heritageLight': ['amber-light'],
  'color/bg':            ['surface-base'],
  'color/raised':        ['surface-raised'],
  'color/sunken':        ['surface-sunken'],
  'color/textBody':      ['text-body'],
  'color/textMuted':     ['text-secondary'],
  'color/borderSubtle':  ['border', 'border-subtle'],
  'color/borderStrong':  ['border-strong'],
  'color/darkDeep':      ['surface-dark-deep'],
  'color/onDark':        ['text-on-dark'],
};

// --- Load the snapshot and index it by Figma variable name ---
const snapshot = JSON.parse(readFileSync(IN, 'utf8'));
const valueOf = Object.fromEntries(
  snapshot.tokens.filter((t) => t.type === 'COLOR').map((t) => [t.name, t.value]),
);

// --- Apply the contract; fail loudly if Figma is missing a mapped token ---
const rows = [];
const missing = [];
for (const [figmaName, scssKeys] of Object.entries(COLOR_MAP)) {
  const value = valueOf[figmaName];
  if (!value) { missing.push(figmaName); continue; }
  for (const key of scssKeys) rows.push(`  ${key}: ${value},`);
}
if (missing.length) {
  console.error(`ERROR: figma-tokens.json is missing: ${missing.join(', ')}`);
  console.error('Refresh the snapshot from Figma, then re-run.');
  process.exit(1);
}

// --- Emit the generated partial ---
const scss = `// GENERATED by scripts/sync-figma-tokens.mjs -- do not edit by hand.
// Source of truth: Figma "Sam Wong - Brand System" (core brand colours).
// To change a value: edit it in Figma, refresh figma-tokens.json, re-run the script.

$figma-tokens: (
${rows.join('\n')}
);
`;

writeFileSync(OUT, scss, 'utf8');
console.log(`Wrote ${rows.length} core brand colours -> ${relative(ROOT, OUT)}`);
